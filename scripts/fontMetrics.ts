import fontkit from "@pdf-lib/fontkit";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { FONTS } from "@/lib/render/fonts";
import { METRIC_CHARS } from "@/lib/render/metrics";

/**
 * Builds src/lib/render/fontMetricsData.ts from the bundled font files:
 * advance widths (thousandths of an em) for the characters cover layout
 * measures, plus cap height. Run `npm run font-metrics` after adding or
 * changing a font; tests/font-metrics.test.ts fails while the file is stale.
 */

export const METRICS_FILE = path.join(process.cwd(), "src/lib/render/fontMetricsData.ts");

export async function buildFontMetricsSource(): Promise<string> {
  const files = [...new Set(FONTS.flatMap((f) => [f.regular, f.bold].filter((x): x is string => Boolean(x))))];
  const entries: string[] = [];
  for (const file of files) {
    const font = fontkit.create(new Uint8Array(await readFile(path.join(process.cwd(), "public/fonts", file))));
    const em = font.unitsPerEm;
    const widths = [...METRIC_CHARS].map((ch) => Math.round((font.glyphForCodePoint(ch.codePointAt(0)!).advanceWidth * 1000) / em));
    entries.push(`  ${JSON.stringify(file)}: { capHeight: ${Math.round((font.capHeight * 1000) / em)}, widths: [${widths.join(",")}] },`);
  }
  return `// Generated by \`npm run font-metrics\` from public/fonts. Do not edit by hand.
import type { FontMetrics } from "./metrics";

export const FONT_METRICS: Record<string, FontMetrics> = {
${entries.join("\n")}
};
`;
}
