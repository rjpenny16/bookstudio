/**
 * Topic banks for offline journals: prompts and affirmations written for a
 * particular reader (nurses, teachers, new parents, travelers…). A book whose
 * topic or audience matches a bank draws on it first, before the general banks
 * in `offlineBanks.ts`. Prompts are split by where they look (back, now,
 * ahead) so a journal's "Looking Back", "Right Now" and "Looking Ahead"
 * sections each get their share. The content checks in `quality/content.ts`
 * hold these to the same standard as model output.
 */

export type Orientation = "back" | "now" | "ahead";

export interface PromptTopic {
  id: string;
  /** Matched against the book's topic, audience and section title. */
  match: RegExp;
  prompts: Record<Orientation, string[]>;
}

export interface AffirmationTopic {
  id: string;
  match: RegExp;
  affirmations: string[];
}

